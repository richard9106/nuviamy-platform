const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context=vm.createContext({document:{querySelectorAll:()=>[]},Date,Number,Set,Error});
vm.runInContext(fs.readFileSync('static/appointment-recurrence.js','utf8'),context);
const plan=(...args)=>JSON.parse(vm.runInContext(`JSON.stringify(appointmentRecurrenceDates(...${JSON.stringify(args)}))`,context));
assert.deepEqual(plan('2026-11-16T10:00',2,[0,2],'count',5,''),['2026-11-16','2026-11-18','2026-11-30','2026-12-02','2026-12-14']);
assert.deepEqual(plan('2026-11-18T10:00',1,[0,2],'date',0,'2026-11-25'),['2026-11-18','2026-11-23','2026-11-25']);
assert.throws(()=>plan('2026-11-16T10:00',1,[],'count',4,''));
assert.throws(()=>plan('2026-11-16T10:00',1,[1],'count',4,''));
assert.throws(()=>plan('2026-11-16T10:00',1,[0],'date',0,'2030-01-01'));
assert.equal(plan('2026-12-28T10:00',1,[0],'count',2,'')[1],'2027-01-04');
console.log('Recurrence preview: weekdays, interval, inclusive end date, year rollover and 52-session limit passed.');
// Native checkboxes emit input before change; a new selection must survive that first event.
const control = (value,name='') => ({value,name,checked:false,disabled:false,handlers:{},addEventListener(type,fn){(this.handlers[type] ||= []).push(fn);}});
const days=[0,1,2,3,4,5,6].map(day=>control(String(day),'recurrence_weekdays'));
const fields={recurrence_rule:control('weekly'),starts_at:control('2026-11-16T10:00'),recurrence_interval:control('1'),recurrence_ends:control('count'),repeat_weekly_count:control('4'),recurrence_until:control('')};
const settings={querySelectorAll:()=>[fields.recurrence_interval,fields.recurrence_ends,fields.repeat_weekly_count,fields.recurrence_until,...days]};
const title={},preview={children:[],replaceChildren(){this.children=[];},append(node){this.children.push(node);}},button={textContent:'Create appointment'};
const countPanel={},datePanel={};
const form={elements:fields,handlers:{},querySelector:()=>button,closest:()=>null,addEventListener(type,fn){(this.handlers[type] ||= []).push(fn);}};
const editor={closest:()=>form,querySelectorAll:()=>days,querySelector:selector=>({'[data-recurrence-settings]':settings,'[data-recurrence-count]':countPanel,'[data-recurrence-date]':datePanel,'[data-recurrence-preview-title]':title,'[data-recurrence-preview-dates]':preview}[selector])};
vm.runInNewContext(fs.readFileSync('static/appointment-recurrence.js','utf8'),{document:{querySelectorAll:()=>[editor],createElement:()=>({})},Date,Number,Set,Error,Intl});
assert.equal(days[0].checked,true,'The first start weekday is preselected');
days[2].checked=true;
(days[2].handlers.input||[]).forEach(fn=>fn());
form.handlers.input.forEach(fn=>fn());
assert.equal(days[2].checked,true,'The input event must retain a newly selected second weekday');
assert.match(preview.children[1].textContent,/Wed/);
assert.equal(button.textContent,'Create 4 appointments');
console.log('Recurrence controls preserve multi-day selection on the first native input event.');
